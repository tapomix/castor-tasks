<?php

declare(strict_types=1);

namespace Tapomix\Castor\Traefik;

use Castor\Attribute\AsArgument;
use Castor\Attribute\AsOption;
use Castor\Attribute\AsTask;
use Castor\Exception\ProblemException;
use Castor\Helper\PathHelper;

use function Castor\fs;
use function Castor\io;
use function Castor\yaml_dump;
use function Castor\yaml_parse;

define('TAPOMIX_NAMESPACE_TRAEFIK', 'tapomix-traefik');

/* Site networks, a compose file owned by the traefik:site tasks: parsed and rewritten whole. */
define('TAPOMIX_TRAEFIK_SITES_FILE', 'compose.sites.yaml');

const PUPPETEER_ALIAS = 'puppeteer';

// the comments live here: the file is rewritten whole, a comment added by hand would be lost
const SITES_FILE_HEADER = <<<'YAML'
    # generated by `castor traefik:site:*`: do not edit by hand
    #
    # one network per site, consumed by the site as external: a site not declared here refuses to start
    # every site network is internal: no route to the internet through it, a site that needs one adds its own egress network
    # the `puppeteer` alias, only on the sites that use it: the site reaches Puppeteer through Traefik under that name
    # ! a change to a network definition forces its recreation: stop the site, `castor service:update` here, then restart
    #   the site (an alias change only recreates Traefik)

    YAML;

// add, remove and puppeteer edit a committed file: dev only, the config is never edited on the VPS
#[AsTask(name: 'site:add', namespace: TAPOMIX_NAMESPACE_TRAEFIK, description: 'Declare a site network', aliases: ['traefik:site:add'], enabled: EXPR_ENV_DEV)]
function add(
    #[AsArgument(description: 'Site name: the CONTAINER_NAME of the site')]
    string $site,
    #[AsOption(description: 'Let the site reach Puppeteer')]
    bool $puppeteer = false,
): void {
    validateSiteName($site);
    writeSites(withSite(readSites(), $site, $puppeteer));

    io()->success(\sprintf('Site "%s" declared in %s%s.', $site, TAPOMIX_TRAEFIK_SITES_FILE, $puppeteer ? ', with Puppeteer' : ''));
    io()->text('Next steps:');
    io()->listing([
        \sprintf('review and commit %s, then push', TAPOMIX_TRAEFIK_SITES_FILE),
        'on the VPS: castor service:update (Traefik is recreated, a short cut for every site)',
        // the site .env already points to it: TRAEFIK_NET=traefik-${CONTAINER_NAME}
        'start the site on the VPS',
    ]);
}

#[AsTask(name: 'site:remove', namespace: TAPOMIX_NAMESPACE_TRAEFIK, description: 'Remove a site network', aliases: ['traefik:site:remove'], enabled: EXPR_ENV_DEV)]
function remove(
    #[AsArgument(description: 'Site name: the CONTAINER_NAME of the site')]
    string $site,
): void {
    validateSiteName($site);
    writeSites(withoutSite(readSites(), $site));

    io()->success(\sprintf('Site "%s" removed from %s.', $site, TAPOMIX_TRAEFIK_SITES_FILE));
    io()->text('Next steps:');
    io()->listing([
        'on the VPS: stop the site',
        \sprintf('review and commit %s, then push', TAPOMIX_TRAEFIK_SITES_FILE),
        'on the VPS: castor service:update',
        // Compose never removes a network it no longer declares
        \sprintf('on the VPS: docker network rm traefik-%s', $site),
    ]);
}

#[AsTask(name: 'site:puppeteer', namespace: TAPOMIX_NAMESPACE_TRAEFIK, description: 'Grant or revoke the Puppeteer access of a site', aliases: ['traefik:site:puppeteer'], enabled: EXPR_ENV_DEV)]
function puppeteer(
    #[AsArgument(description: 'Site name: the CONTAINER_NAME of the site')]
    string $site,
    #[AsOption(description: 'Revoke the access instead of granting it')]
    bool $revoke = false,
): void {
    validateSiteName($site);
    writeSites(withPuppeteer(readSites(), $site, !$revoke));

    io()->success(\sprintf('Puppeteer access %s for site "%s" in %s.', $revoke ? 'revoked' : 'granted', $site, TAPOMIX_TRAEFIK_SITES_FILE));
    io()->text('Next steps:');
    io()->listing([
        \sprintf('review and commit %s, then push', TAPOMIX_TRAEFIK_SITES_FILE),
        // only the alias of Traefik changes: the site network is left as is
        'on the VPS: castor service:update (Traefik is recreated, a short cut for every site; the site keeps running)',
    ]);
}

// `list` is a reserved word: the function name differs from the task name
#[AsTask(name: 'site:list', namespace: TAPOMIX_NAMESPACE_TRAEFIK, description: 'List the declared site networks', aliases: ['traefik:site:list'])]
function listSites(): void
{
    $sites = readSites();

    if ([] === $sites) {
        io()->note(\sprintf('No site declared in %s.', TAPOMIX_TRAEFIK_SITES_FILE));

        return;
    }

    $rows = [];
    foreach ($sites as $site => $puppeteer) {
        $rows[] = [$site, $puppeteer ? '<fg=green>V</>' : '<fg=red>X</>'];
    }

    io()->table(['Site', 'Puppeteer'], $rows);
}

/** @return array<string, bool> site => Puppeteer access */
function readSites(): array
{
    $path = sitesFilePath();

    return fs()->exists($path) ? parseSites((string) \file_get_contents($path)) : [];
}

/** @param array<string, bool> $sites */
function writeSites(array $sites): void
{
    fs()->dumpFile(sitesFilePath(), dumpSites($sites));
}

function sitesFilePath(): string
{
    return PathHelper::getRoot() . '/' . TAPOMIX_TRAEFIK_SITES_FILE;
}

function validateSiteName(string $site): void
{
    if (1 !== \preg_match('/^[a-z0-9-]+$/', $site)) {
        throw new ProblemException(\sprintf('Invalid site name "%s": lowercase letters, digits and dashes only.', $site));
    }
}

/**
 * @param array<string, bool> $sites
 *
 * @return array<string, bool>
 */
function withSite(array $sites, string $site, bool $puppeteer = false): array
{
    validateSiteName($site);

    if (\array_key_exists($site, $sites)) {
        throw new ProblemException(\sprintf('Site "%s" is already declared.', $site));
    }

    $sites[$site] = $puppeteer;
    \ksort($sites, \SORT_STRING);

    return $sites;
}

/**
 * @param array<string, bool> $sites
 *
 * @return array<string, bool>
 */
function withoutSite(array $sites, string $site): array
{
    validateSiteName($site);

    if (!\array_key_exists($site, $sites)) {
        throw new ProblemException(\sprintf('Site "%s" is not declared.', $site));
    }

    unset($sites[$site]);

    return $sites;
}

/**
 * @param array<string, bool> $sites
 *
 * @return array<string, bool>
 */
function withPuppeteer(array $sites, string $site, bool $puppeteer): array
{
    validateSiteName($site);

    if (!\array_key_exists($site, $sites)) {
        throw new ProblemException(\sprintf('Site "%s" is not declared.', $site));
    }

    if ($sites[$site] === $puppeteer) {
        throw new ProblemException(\sprintf('Site "%s" %s Puppeteer already.', $site, $puppeteer ? 'reaches' : 'does not reach'));
    }

    $sites[$site] = $puppeteer;

    return $sites;
}

/** @return array<string, bool> site => Puppeteer access */
function parseSites(string $yaml): array
{
    $config = yaml_parse($yaml);
    $networks = \is_array($config) && \is_array($config['networks'] ?? null) ? $config['networks'] : [];
    $attachments = \is_array($config) ? ($config['services']['traefik']['networks'] ?? []) : [];

    $sites = [];
    foreach (\array_keys($networks) as $key) {
        $key = (string) $key;
        if (!\str_ends_with($key, '-net')) {
            continue;
        }

        $aliases = \is_array($attachments) && \is_array($attachments[$key] ?? null) ? ($attachments[$key]['aliases'] ?? []) : [];
        $sites[\substr($key, 0, -\strlen('-net'))] = \is_array($aliases) && \in_array(PUPPETEER_ALIAS, $aliases, true);
    }

    \ksort($sites, \SORT_STRING);

    return $sites;
}

/** @param array<string, bool> $sites */
function dumpSites(array $sites): string
{
    \ksort($sites, \SORT_STRING);

    $serviceNetworks = [];
    $networks = [];

    foreach ($sites as $site => $puppeteer) {
        // without the alias, an empty map: Traefik still joins the network
        $serviceNetworks[$site . '-net'] = $puppeteer ? ['aliases' => [PUPPETEER_ALIAS]] : [];
        $networks[$site . '-net'] = ['internal' => true, 'name' => 'traefik-' . $site];
    }

    $config = [
        'services' => ['traefik' => ['networks' => $serviceNetworks]],
        'networks' => $networks,
    ];

    return SITES_FILE_HEADER . yaml_dump($config, 10, 2);
}
