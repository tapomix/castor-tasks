<?php

namespace Tapomix\Castor\Tests\Unit\Traefik;

use Castor\Exception\ProblemException;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

use function Castor\yaml_parse;
use function Tapomix\Castor\Traefik\dumpSites;
use function Tapomix\Castor\Traefik\parseSites;
use function Tapomix\Castor\Traefik\validateSiteName;
use function Tapomix\Castor\Traefik\withoutSite;
use function Tapomix\Castor\Traefik\withPuppeteer;
use function Tapomix\Castor\Traefik\withSite;

class SitesTest extends TestCase
{
    public function testValidateSiteNameAcceptsLowercaseDigitsAndDashes(): void
    {
        validateSiteName('bank');
        validateSiteName('site-2');

        $this->addToAssertionCount(2);
    }

    /** @return iterable<string, array{string}> */
    public static function invalidNames(): iterable
    {
        yield 'empty' => [''];
        yield 'uppercase' => ['Bank'];
        yield 'underscore' => ['my_site'];
        yield 'dot' => ['a.b'];
        yield 'space' => ['a b'];
    }

    #[DataProvider('invalidNames')]
    public function testValidateSiteNameRejectsInvalidNames(string $site): void
    {
        $this->expectException(ProblemException::class);

        validateSiteName($site);
    }

    public function testWithSiteAddsAndSorts(): void
    {
        $this->assertSame(
            ['bank' => false, 'coaching' => true, 'timing' => false],
            withSite(['timing' => false, 'bank' => false], 'coaching', true),
        );
    }

    public function testWithSiteDefaultsToNoPuppeteer(): void
    {
        $this->assertSame(['bank' => false], withSite([], 'bank'));
    }

    public function testWithSiteRejectsDuplicate(): void
    {
        $this->expectException(ProblemException::class);

        withSite(['bank' => false], 'bank');
    }

    public function testWithSiteRejectsInvalidName(): void
    {
        $this->expectException(ProblemException::class);

        withSite([], 'Bank');
    }

    public function testWithoutSiteRemoves(): void
    {
        $this->assertSame(['timing' => false], withoutSite(['bank' => true, 'timing' => false], 'bank'));
    }

    public function testWithoutSiteRejectsUnknown(): void
    {
        $this->expectException(ProblemException::class);

        withoutSite(['bank' => false], 'timing');
    }

    public function testWithPuppeteerGrants(): void
    {
        $this->assertSame(['bank' => true], withPuppeteer(['bank' => false], 'bank', true));
    }

    public function testWithPuppeteerRevokes(): void
    {
        $this->assertSame(['bank' => false], withPuppeteer(['bank' => true], 'bank', false));
    }

    public function testWithPuppeteerRejectsUnknown(): void
    {
        $this->expectException(ProblemException::class);

        withPuppeteer(['bank' => false], 'timing', true);
    }

    /** @return iterable<string, array{bool}> */
    public static function puppeteerStates(): iterable
    {
        yield 'grant twice' => [true];
        yield 'revoke twice' => [false];
    }

    #[DataProvider('puppeteerStates')]
    public function testWithPuppeteerRejectsNoChange(bool $puppeteer): void
    {
        $this->expectException(ProblemException::class);

        withPuppeteer(['bank' => $puppeteer], 'bank', $puppeteer);
    }

    public function testParseSitesOfEmptyContent(): void
    {
        $this->assertSame([], parseSites(''));
    }

    public function testDumpSitesStartsWithHeader(): void
    {
        $this->assertStringStartsWith('# generated by', dumpSites(['bank' => false]));
    }

    public function testDumpSitesStructure(): void
    {
        $expected = [
            'services' => [
                'traefik' => [
                    'networks' => [
                        'bank-net' => [],
                        'coaching-net' => ['aliases' => ['puppeteer']],
                    ],
                ],
            ],
            'networks' => [
                'bank-net' => ['internal' => true, 'name' => 'traefik-bank'],
                'coaching-net' => ['internal' => true, 'name' => 'traefik-coaching'],
            ],
        ];

        $this->assertSame($expected, yaml_parse(dumpSites(['coaching' => true, 'bank' => false])));
    }

    public function testDumpThenParseRoundTrip(): void
    {
        $this->assertSame(
            ['bank' => false, 'coaching' => true, 'timing' => false],
            parseSites(dumpSites(['timing' => false, 'coaching' => true, 'bank' => false])),
        );
    }

    public function testParseSitesOf050File(): void
    {
        // the 0.5.0 layout: every site with the alias
        $yaml = "services:\n  traefik:\n    networks:\n      bank-net:\n        aliases:\n          - puppeteer\n"
            . "networks:\n  bank-net:\n    internal: true\n    name: traefik-bank\n";

        $this->assertSame(['bank' => true], parseSites($yaml));
    }

    public function testParseSitesOfNullAttachment(): void
    {
        $yaml = "services:\n  traefik:\n    networks:\n      bank-net:\n"
            . "networks:\n  bank-net:\n    internal: true\n    name: traefik-bank\n";

        $this->assertSame(['bank' => false], parseSites($yaml));
    }

    public function testDumpWithoutSitesKeepsMaps(): void
    {
        $yaml = dumpSites([]);

        $this->assertStringNotContainsString('[]', $yaml);
        $this->assertSame(
            ['services' => ['traefik' => ['networks' => []]], 'networks' => []],
            yaml_parse($yaml),
        );
        $this->assertSame([], parseSites($yaml));
    }

    public function testDumpWithoutPuppeteerWritesEmptyMap(): void
    {
        $this->assertStringContainsString("\n      bank-net: {}\n", dumpSites(['bank' => false]));
    }

    public function testDumpUsesBlockStyle(): void
    {
        $this->assertStringContainsString("\n          - puppeteer\n", dumpSites(['bank' => true]));
    }
}
